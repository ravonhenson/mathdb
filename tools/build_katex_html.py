# Called from Swift (LaTeXView) through WebPage.callJavaScript.
# Returns the rendered size so the view can fit its height to the math, and
# whether KaTeX could parse the input (model output isn't always valid LaTeX).
PAGE = """<!doctype html>
<!-- KaTeX {version} (MIT License, see KaTeX-LICENSE.txt). Generated by tools/build_katex_html.py. -->
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>{css}</style>
<style>
:root {{ color-scheme: light dark; }}
html, body {{ margin: 0; padding: 0; background: transparent; -webkit-text-size-adjust: none; }}
#math {{ display: inline-block; box-sizing: border-box; min-width: 100%; padding: 6px 12px; text-align: center; }}
.katex-display {{ margin: 0; }}
</style>
<script>{js}</script>
<script>
async function render(latex, fontSize) {{
  const el = document.getElementById('math');
  el.style.fontSize = fontSize + 'px';
  let ok = true, message = '';
  try {{
    katex.render(latex, el, {{ displayMode: true, throwOnError: true, strict: 'ignore' }});
  }} catch (e) {{
    ok = false;
    message = String(e.message || e);
    katex.render(latex, el, {{ displayMode: true, throwOnError: false, errorColor: '#d33', strict: 'ignore' }});
  }}
  await document.fonts.ready;  // measure only once the embedded fonts are in use
  return {{ ok: ok, message: message, width: Math.ceil(el.scrollWidth), height: Math.ceil(el.scrollHeight) }};
}}
</script>
</head><body><div id="math"></div></body></html>
"""


def inline_fonts(css: str, fonts: Path) -> str:
    """Replace each @font-face src list with a single embedded WOFF2."""
    def replace(match: re.Match) -> str:
        name = match.group(1)
        data = base64.b64encode((fonts / f"{name}.woff2").read_bytes()).decode()
        return f'src:url(data:font/woff2;base64,{data}) format("woff2")'

    out, count = re.subn(r'src:url\(fonts/([\w-]+)\.woff2\) format\("woff2"\)[^;}]*', replace, css)
    if count == 0:
        raise SystemExit("No @font-face rules found; has the KaTeX CSS format changed?")
    return out


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    katex = Path(sys.argv[1]).expanduser()
    js = (katex / "katex.min.js").read_text()
    css = inline_fonts((katex / "katex.min.css").read_text(), katex / "fonts")
    if "</script" in js.lower():
        js = re.sub(r"</(script)", r"<\\/\1", js, flags=re.IGNORECASE)
    version = re.search(r'version:"([\d.]+)"', js)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    html = PAGE.format(version=version.group(1) if version else "?", css=css, js=js)
    (OUT_DIR / "katex.html").write_text(html)
    (OUT_DIR / "KaTeX-LICENSE.txt").write_text(LICENSE)
    print(f"wrote {OUT_DIR / 'katex.html'} ({len(html) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
